"""gate_names.py -- the names only REPENTOGON has, for the layer's gate (round 122).

  python -I scripts/recomp/rgon/tools/gate_names.py [--check]

Writes scripts/recomp/rgon/gate_names.lua: every function name REPENTOGON
registers with Lua (a `{ "Name", Lua_... }` row of its sources) and every
global table it adds, less the names the executable or the game's own scripts
contain. The layer's gate (rgon.lua) reads it to tell which of the names a mod
uses are REPENTOGON's; which of those it has, it knows itself.

Names are facts about an interface, not code; none of REPENTOGON's code is
read into the layer. Callbacks are not listed: enums_ex.lua, which ships with
the layer, has them with their numbers.

--check writes nothing and exits 1 if the file on disk is not what would be
written (a test runs it, so a REPENTOGON submodule bump cannot go unnoticed).
"""
import io
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..', '..'))
RG = os.path.join(ROOT, 'third_party', 'REPENTOGON')
GAME = os.environ.get('ISAAC_GAME_DIR', 'C:/Program Files (x86)/Steam/steamapps/common/The Binding of Isaac Rebirth')
OUT = os.path.join(ROOT, 'scripts', 'recomp', 'rgon', 'gate_names.lua')
IDENT = re.compile(r'[A-Za-z_][A-Za-z0-9_]{2,}')

# the global tables REPENTOGON adds (its documentation's class list)
GLOBALS = """ImGui XMLData EntityConfig RoomConfig RoomConfigHolder PersistentGameData MenuManager MainMenu CharacterMenu
StatsMenu TitleMenu SaveMenu OptionsMenu ModsMenu SpecialSeedsMenu PauseMenu Console DebugRenderer ProceduralItemManager
BossPoolManager ItemOverlay RoomTransition NightmareScene StageTransition Minimap Ambush ScoreSheet DailyChallenge
Beam Capsule GenericPrompt LootList WeightedOutcomePicker CompletionWidget HistoryHUD LevelGenerator
EntitySaveStateManager ColorParams FXParams SourceQuad DestinationQuad BestiaryMenu ChallengeMenu CollectionMenu
ControllerSelectMenu CustomChallengeMenu CutscenesMenu DailyChallengeMenu KeyConfigMenu JoinGameMenu BonusRoundMenu
OnlineLobbyMenu OnlineMenu RailManager NullFrame PlayerManager MultiShotParams""".split()


def walk(d, ext):
    for base, _, names in os.walk(d):
        for n in names:
            if n.lower().endswith(ext):
                yield os.path.join(base, n)


def read(p):
    with io.open(p, encoding='utf-8', errors='replace') as f:
        return f.read()


def wrap(names, width=100):
    lines, cur = [], ''
    for n in names:
        if cur and len(cur) + 1 + len(n) > width:
            lines.append(cur)
            cur = n
        else:
            cur = (cur + ' ' + n) if cur else n
    if cur:
        lines.append(cur)
    return '\n'.join(lines)


def main():
    fns = set()
    for f in walk(os.path.join(RG, 'repentogon'), '.cpp'):
        for m in re.finditer(r'\{\s*"([A-Za-z_][A-Za-z0-9_]*)"\s*,\s*[A-Za-z_:][A-Za-z0-9_:]*\s*\}', read(f)):
            fns.add(m.group(1))
    vanilla = set()
    with open(os.path.join(ROOT, 'tools', 'isaac-ng.unpacked.exe'), 'rb') as f:
        vanilla.update(IDENT.findall(f.read().decode('latin1')))
    scripts = list(walk(os.path.join(GAME, 'resources', 'scripts'), '.lua'))
    if not scripts:
        sys.exit('gate_names.py: no game scripts under %s (set ISAAC_GAME_DIR)' % GAME)
    for f in scripts:
        vanilla.update(IDENT.findall(read(f)))
    only = sorted(n for n in fns if n not in vanilla and len(n) > 2)
    globs = sorted(g for g in GLOBALS if g not in vanilla)
    body = ('-- gate_names.lua -- generated by tools/gate_names.py; do not edit.\n'
            '-- The names only REPENTOGON has: %d function names it registers with Lua and %d global\n'
            '-- tables it adds, less everything the executable or the game\'s own scripts contain. The\n'
            '-- gate (rgon.lua) reads this to tell which of the names a mod uses are REPENTOGON\'s.\n'
            'return {\n  fns = [[\n%s\n]],\n  globals = [[\n%s\n]],\n}\n') % (len(only), len(globs), wrap(only), wrap(globs))
    if '--check' in sys.argv:
        try:
            have = io.open(OUT, encoding='utf-8', newline='').read().replace('\r\n', '\n')
        except OSError:
            have = None
        if have != body:
            sys.exit('gate_names.lua is not what gate_names.py writes: run it again')
        print('gate_names.lua: %d function names, %d globals (up to date)' % (len(only), len(globs)))
        return
    io.open(OUT, 'w', encoding='utf-8', newline='\n').write(body)
    print('%s: %d function names, %d globals' % (OUT, len(only), len(globs)))


main()
